"""Tests for the "Check our work" validation assets.

validation.json is generated by pipeline/build_validation.py. These tests make
sure every case is sourced, that its status really follows from its own
stated numbers and rule, and that rebuilding is deterministic.

Run with: python -m pytest tests/reference_cases/test_validation.py -q
"""
import importlib.util
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
VALIDATION = ROOT / "frontend" / "public" / "data" / "validation.json"
sys.path.insert(0, str(ROOT / "pipeline"))


def _load_builder():
    spec = importlib.util.spec_from_file_location("build_validation", ROOT / "pipeline" / "build_validation.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture(scope="module")
def doc():
    assert VALIDATION.exists(), "run python pipeline/build_validation.py"
    return json.loads(VALIDATION.read_text(encoding="utf-8"))


def test_enough_cases_and_summary_consistent(doc):
    cases = doc["cases"]
    assert 5 <= len(cases) <= 12
    scored = [c for c in cases if c["status"] in ("pass", "partial", "fail")]
    s = doc["summary"]
    assert s["scored"] == len(scored)
    for k in ("pass", "partial", "fail"):
        assert s[k] == sum(1 for c in scored if c["status"] == k)
    assert s["not_comparable"] == sum(1 for c in cases if c["status"] == "not-comparable")


def test_every_case_has_source_url_rule_and_explanation(doc):
    ids = set()
    for c in doc["cases"]:
        assert c["id"] not in ids
        ids.add(c["id"])
        assert c["sources"], c["id"]
        for src in c["sources"]:
            assert src["url"].startswith("https://"), c["id"]
            assert src["citation"], c["id"]
        assert c["rule"] and c["explanation"] and c["question"], c["id"]
        assert c["status"] in ("pass", "partial", "fail", "not-comparable")


def _range_status(v, lo, hi, tol):
    if lo <= v <= hi:
        return "pass"
    edge = lo if v < lo else hi
    if v * edge > 0 and abs(v - edge) <= tol * abs(edge):
        return "partial"
    return "fail"


def test_status_follows_stated_rule(doc):
    b = _load_builder()
    by_id = {c["id"]: c for c in doc["cases"]}

    c = by_id["global-warming-rate"]
    assert c["status"] == _range_status(c["our"]["value"], c["reference"]["low"], c["reference"]["high"], b.TOL_GLOBAL)

    c = by_id["arctic-amplification"]
    assert (c["reference"]["low"], c["reference"]["high"]) == b.AA_RANGE
    assert c["status"] == _range_status(c["our"]["value"], *b.AA_RANGE, b.TOL_ARCTIC)

    c = by_id["de-bilt-century-warming"]
    assert c["status"] == _range_status(c["our"]["value"], *b.DEBILT_RANGE, b.TOL_DEBILT)

    c = by_id["ocean-sst-warming"]
    assert c["status"] == _range_status(c["our"]["value"], *b.SST_RANGE, b.TOL_SST)

    c = by_id["station-vs-reanalysis"]
    o, r = c["our"], c["reference"]
    overlap = max(o["ci_low"], r["low"]) <= min(o["ci_high"], r["high"])
    close = abs(o["value"] - r["value"]) <= b.TOL_STATION * abs(r["value"])
    assert c["status"] == ("pass" if overlap and close else "partial" if overlap else "fail")

    c = by_id["india-no2-2005-2015"]
    v = c["our"]["value"]
    assert c["status"] == ("pass" if v >= b.NO2_PASS else "partial" if v >= b.NO2_PARTIAL else "fail")

    for cid in ("precip-merra2-vs-gpcp", "precip-imerg-vs-gpcp"):
        c = by_id[cid]
        rows = c["details"]["rows"]
        frac = sum(1 for r in rows if r[-1]) / len(rows)
        assert abs(c["our"]["value"] - 100 * frac) < 1e-3
        assert c["status"] == ("pass" if frac >= b.P_PASS else "partial" if frac >= b.P_PARTIAL else "fail")

    c = by_id["seawifs-river-chlorophyll"]
    assert c["status"] == "not-comparable" and c["our"]["value"] is None


def test_reference_values_match_cited_figures(doc):
    """The literature figures verified from the primary sources on 2026-11-15."""
    by_id = {c["id"]: c for c in doc["cases"]}
    assert by_id["arctic-amplification"]["reference"]["value"] == 3.8  # Rantanen 2022
    assert by_id["ocean-sst-warming"]["reference"]["low"] == 0.108     # Menemenlis 2025
    assert by_id["ocean-sst-warming"]["reference"]["high"] == 0.184
    assert by_id["india-no2-2005-2015"]["reference"]["low"] == 50      # Krotkov 2016


def test_rebuild_is_deterministic(tmp_path, doc):
    b = _load_builder()
    b.OUT = tmp_path / "validation.json"
    b.main()
    assert b.OUT.read_text(encoding="utf-8") == VALIDATION.read_text(encoding="utf-8")


def test_independent_reference_series_complete():
    b = _load_builder()
    for d in (b.GISTEMP, b.NOAAGT, b.HADCRUT5):
        assert sorted(d) == list(range(1981, 2026))
